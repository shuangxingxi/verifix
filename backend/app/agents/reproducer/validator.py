from __future__ import annotations

import ast

from app.domain.defects.plugins import AssertionPolicy

FORBIDDEN_IMPORTS = frozenset({"requests", "urllib", "socket", "httpx", "aiohttp"})
FORBIDDEN_CALLS = frozenset(
    {
        "urlopen",
        "get",
        "post",
        "connect",
        "create_connection",
    }
)
FORBIDDEN_CALL_QUALIFIERS = frozenset({"requests", "urllib", "socket", "httpx", "aiohttp"})
SKIP_DECORATORS = frozenset({"skip", "skipIf", "skipUnless", "xfail"})


class InvalidTestError(ValueError):
    def __init__(self, issues: list[str]):
        self.issues = issues
        super().__init__("invalid reproduction test: " + "; ".join(issues))


def _decorator_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Call):
        node = node.func
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Name):
        return node.id
    return None


def validate_test_source(source: str, policy: AssertionPolicy | None = None) -> list[str]:
    problems: list[str] = []
    if "AUTOGENERATED" not in source:
        problems.append("missing AUTOGENERATED marker")
    if "assert True" in source:
        problems.append("forbidden constant assertion: assert True")
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        return problems + [f"syntax error: {exc.msg}"]

    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            names = []
            if isinstance(node, ast.Import):
                names = [alias.name.split(".")[0] for alias in node.names]
            elif node.module:
                names = [node.module.split(".")[0]]
            for name in names:
                if name in FORBIDDEN_IMPORTS:
                    problems.append(f"external network dependency: import {name}")
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for decorator in node.decorator_list:
                name = _decorator_name(decorator)
                if name in SKIP_DECORATORS:
                    problems.append(f"forbidden skip marker: {name}")
                if isinstance(decorator, ast.Attribute) and decorator.attr in SKIP_DECORATORS:
                    problems.append(f"forbidden skip marker: pytest.{decorator.attr}")
        if isinstance(node, ast.Assert):
            if isinstance(node.test, ast.Constant) and node.test.value is True:
                problems.append("forbidden constant assertion: assert True")
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Attribute):
                if func.attr in FORBIDDEN_CALLS and isinstance(func.value, ast.Name):
                    if func.value.id in FORBIDDEN_CALL_QUALIFIERS:
                        problems.append(f"external network call: {func.value.id}.{func.attr}")
                if func.attr in FORBIDDEN_CALLS and isinstance(func.value, ast.Attribute):
                    if isinstance(func.value.value, ast.Name) and func.value.value.id in FORBIDDEN_CALL_QUALIFIERS:
                        problems.append(f"external network call: {func.value.value.id}.{func.value.attr}.{func.attr}")

    if policy is not None:
        for marker in policy.forbidden_markers:
            if marker in source:
                problems.append(f"forbidden marker from policy: {marker}")
    return problems


def assert_valid(source: str, policy: AssertionPolicy | None = None) -> None:
    problems = validate_test_source(source, policy)
    if problems:
        raise InvalidTestError(problems)