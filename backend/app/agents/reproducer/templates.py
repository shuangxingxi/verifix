from __future__ import annotations

import ast
from dataclasses import dataclass
from pathlib import Path

from app.domain.enums import DefectClass
from app.domain.models import Alert, Issue

MARKER = "AUTOGENERATED"
TAIL = '\n\nif __name__ == "__main__":\n    unittest.main()\n'

SQL_CALLS: dict[str, tuple[str, str, str]] = {
    "/user": ("get", "uid", "1' OR '1'='1"),
    "/search": ("get", "q", "a' OR 1=1 -- "),
    "/order": ("get", "order_id", "1 OR 1=1"),
    "/report": ("get", "day", "1' OR '1'='1"),
    "/profile": ("get", "id", "1 OR 1=1"),
    "/login": ("post", "username", "' OR '1'='1' -- "),
}


@dataclass(frozen=True)
class GeneratedTest:
    relative_path: str
    source: str
    behavior: str
    test_name: str


def _relative_test_path(issue_id: str) -> str:
    return f"tests/security/test_{issue_id.lower().replace('-', '_')}.py"


def _header(issue: Issue, alert: Alert) -> str:
    return (
        f"# {MARKER} issue={issue.issue_id} rule={alert.rule_id} "
        f"defect={issue.defect_class.value if issue.defect_class else 'NA'}\n"
    )


def _function_span(tree: ast.AST, line: int) -> ast.FunctionDef | ast.AsyncFunctionDef | None:
    matches = [
        node
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and node.lineno <= line <= getattr(node, "end_lineno", node.lineno)
    ]
    if not matches:
        return None
    return min(matches, key=lambda node: getattr(node, "end_lineno", node.lineno) - node.lineno)


def _route_of(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str | None:
    for decorator in node.decorator_list:
        if not isinstance(decorator, ast.Call):
            continue
        if decorator.args and isinstance(decorator.args[0], ast.Constant) and isinstance(decorator.args[0].value, str):
            return decorator.args[0].value
    return None


def route_and_method(source_file: Path, line: int) -> tuple[str, str, str] | None:
    try:
        tree = ast.parse(source_file.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return None
    node = _function_span(tree, line)
    if node is None:
        return None
    route = _route_of(node)
    if not route:
        return None
    method = "get"
    for decorator in node.decorator_list:
        if isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Attribute):
            if decorator.func.attr in {"post", "put", "patch"}:
                method = decorator.func.attr
    parameter = SQL_CALLS.get(route, (method, "q", "x' OR '1'='1"))[1]
    return route, method, parameter


def _sql_test(issue: Issue, alert: Alert, target_root: Path) -> GeneratedTest:
    entry = route_and_method(target_root / alert.location.file, alert.location.line or 1)
    route, method, parameter = entry if entry else ("/user", "get", "uid")
    payload = SQL_CALLS.get(route, (method, parameter, "1' OR '1'='1"))[2]
    test_name = f"test_{issue.issue_id.lower().replace('-', '_')}_blocks_injection"
    if method == "post":
        request_line = f"response = self.client.post({route!r}, data={{{parameter!r}: {payload!r}}})"
    else:
        request_line = f"response = self.client.get({route!r}, query_string={{{parameter!r}: {payload!r}}})"

    if route == "/report":
        assertion = 'self.assertLessEqual(int(data[0][0]), 1, f"注入成功，聚合计数为 {data[0][0]}")'
    elif route == "/login":
        assertion = 'self.assertLessEqual(int(data.get("matched", 0)), 1, f"注入成功，匹配 {data.get(\'matched\')} 条")'
    else:
        assertion = 'self.assertLessEqual(len(data), 1, f"注入成功，返回 {len(data)} 条记录")'

    source = (
        _header(issue, alert)
        + "from __future__ import annotations\n\n"
        + "import sys\n"
        + "import tempfile\n"
        + "import unittest\n"
        + "from pathlib import Path\n\n"
        + "ROOT = Path(__file__).resolve().parents[2]\n"
        + "sys.path.insert(0, str(ROOT))\n\n"
        + "import init_db\n\n\n"
        + "class GeneratedReproductionTest(unittest.TestCase):\n"
        + "    def setUp(self):\n"
        + "        self.tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)\n"
        + '        database = Path(self.tmp.name) / "target.db"\n'
        + "        init_db.create(database)\n"
        + "        from app.main import create_app\n"
        + "        self.client = create_app(str(database)).test_client()\n\n"
        + "    def tearDown(self):\n"
        + "        self.tmp.cleanup()\n\n"
        + f"    def {test_name}(self):\n"
        + f"        {request_line}\n"
        + "        data = response.get_json()\n"
        + f"        {assertion}\n"
        + TAIL
    )
    return GeneratedTest(
        relative_path=_relative_test_path(issue.issue_id),
        source=source,
        behavior="behavioral",
        test_name=test_name,
    )


def _static_test(issue: Issue, alert: Alert, markers: list[str], label: str) -> GeneratedTest:
    test_name = f"test_{issue.issue_id.lower().replace('-', '_')}_removes_{label}"
    relative_file = alert.location.file
    line = alert.location.line or 1
    source = (
        _header(issue, alert)
        + "from __future__ import annotations\n\n"
        + "import pathlib\n"
        + "import unittest\n\n\n"
        + "class GeneratedReproductionTest(unittest.TestCase):\n"
        + f"    def {test_name}(self):\n"
        + f"        target = pathlib.Path({relative_file!r})\n"
        + '        lines = target.read_text(encoding="utf-8").splitlines()\n'
        + f'        line = lines[{line} - 1] if {line} <= len(lines) else ""\n'
        + f"        for marker in {markers!r}:\n"
        + '            self.assertNotIn(marker, line, f"危险调用仍存在：{marker}")\n'
        + TAIL
    )
    return GeneratedTest(
        relative_path=_relative_test_path(issue.issue_id),
        source=source,
        behavior="static",
        test_name=test_name,
    )


def _secret_test(issue: Issue, alert: Alert) -> GeneratedTest:
    test_name = f"test_{issue.issue_id.lower().replace('-', '_')}_removes_hardcoded_secret"
    line = alert.location.line or 1
    source = (
        _header(issue, alert)
        + "from __future__ import annotations\n\n"
        + "import pathlib\n"
        + "import re\n"
        + "import unittest\n\n\n"
        + "class GeneratedReproductionTest(unittest.TestCase):\n"
        + f"    def {test_name}(self):\n"
        + f'        lines = pathlib.Path({alert.location.file!r}).read_text(encoding="utf-8").splitlines()\n'
        + f'        line = lines[{line} - 1] if {line} <= len(lines) else ""\n'
        + "        self.assertIsNone(\n"
        + "            re.search(r\"=\\s*[\\\"'][^\\\"']{6,}[\\\"']\", line),\n"
        + '            f"仍存在字面量凭据：{line}",\n'
        + "        )\n"
        + TAIL
    )
    return GeneratedTest(
        relative_path=_relative_test_path(issue.issue_id),
        source=source,
        behavior="static",
        test_name=test_name,
    )


def _dependency_test(issue: Issue, alert: Alert) -> GeneratedTest:
    test_name = f"test_{issue.issue_id.lower().replace('-', '_')}_upgrades_dependency"
    component = alert.location.component or "unknown"
    version = alert.location.component_version or "0.0.0"
    source = (
        _header(issue, alert)
        + "from __future__ import annotations\n\n"
        + "import pathlib\n"
        + "import unittest\n\n\n"
        + "class GeneratedReproductionTest(unittest.TestCase):\n"
        + f"    def {test_name}(self):\n"
        + '        content = pathlib.Path("requirements.txt").read_text(encoding="utf-8")\n'
        + f'        self.assertNotIn({f"{component}=={version}"!r}, content, "依赖版本仍处于受影响区间")\n'
        + TAIL
    )
    return GeneratedTest(
        relative_path=_relative_test_path(issue.issue_id),
        source=source,
        behavior="static",
        test_name=test_name,
    )


def render_test(issue: Issue, alert: Alert, target_root: Path) -> GeneratedTest:
    defect = issue.defect_class
    if defect is DefectClass.SQL_INJECTION:
        return _sql_test(issue, alert, target_root)
    if defect is DefectClass.COMMAND_INJECTION:
        return _static_test(issue, alert, ["os.popen", "shell=True"], "command_injection")
    if defect is DefectClass.HARDCODED_SECRET:
        return _secret_test(issue, alert)
    if defect is DefectClass.DEPENDENCY_CVE:
        return _dependency_test(issue, alert)
    raise ValueError(f"unsupported defect class: {defect}")