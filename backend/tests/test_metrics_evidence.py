class TransactionRollbackTest(unittest.TestCase):
    def setUp(self) -> None:
        self.store = MemoryStore()
        make_issue(self.store, "ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        self.store.add_proof(make_proof("ISS-1"))
        self.store.add_patch(make_patch("ISS-1"))

    def test_attempt_collections_roll_back_and_existing_collections_untouched(self) -> None:
        self.assertIn("reproduction_attempts", SNAPSHOT_COLLECTIONS)
        before = {name: len(getattr(self.store, name)) for name in SNAPSHOT_COLLECTIONS}
        with self.assertRaises(RuntimeError):
            with self.store.transaction():
                self.store.record_reproduction(
                    ReproductionAttempt(
                        attempt_id="RA-ISS-1#1",
                        issue_id="ISS-1",
                        attempt_index=1,
                        status=ReproductionAttemptStatus.PROVEN,
                    )
                )
                self.store.record_patch(
                    PatchAttempt(attempt_id="PA-ISS-1#1", issue_id="ISS-1", attempt_index=1, patch_id="PA-ISS-1")
                )
                self.store.record_gate(
                    GateAttempt(attempt_id="GA-PA-ISS-1#1", patch_id="PA-ISS-1", issue_id="ISS-1")
                )
                self.store.record_disposition(
                    DispositionHistoryEntry(issue_id="ISS-1", level=DispositionLevel.L1)
                )
                raise RuntimeError("boom")
        self.assertEqual(self.store.reproduction_attempts, {})
        self.assertEqual(self.store.patch_attempts, {})
        self.assertEqual(self.store.gate_attempts, {})
        self.assertEqual(self.store.disposition_history, {})
        for name in SNAPSHOT_COLLECTIONS:
            if name in {"reproduction_attempts", "patch_attempts", "gate_attempts", "disposition_history"}:
                continue
            self.assertEqual(len(getattr(self.store, name)), before[name], name)
        self.assertIsNotNone(self.store.proof_for("ISS-1"))
        self.assertIsNotNone(self.store.patch_for("ISS-1"))

    def test_attempt_collections_commit_on_success(self) -> None:
        with self.store.transaction():
            self.store.record_reproduction(
                ReproductionAttempt(
                    attempt_id="RA-ISS-1#1",
                    issue_id="ISS-1",
                    attempt_index=1,
                    status=ReproductionAttemptStatus.PROVEN,
                )
            )
        self.assertEqual(len(self.store.reproduction_attempts_for("ISS-1")), 1)


class AttemptHistoryTest(unittest.TestCase):
    def test_reproduction_attempts_append_while_proof_stays_latest(self) -> None:
        store = MemoryStore()
        make_issue(store, "ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        first = make_proof("ISS-1", "1")
        store.add_proof(first)
        store.record_reproduction(
            ReproductionAttempt(
                attempt_id="RA-ISS-1#1",
                issue_id="ISS-1",
                attempt_index=store.next_reproduction_index("ISS-1"),
                status=ReproductionAttemptStatus.PROVEN,
                proof_id=first.proof_id,
            )
        )
        second = make_proof("ISS-1", "2")
        store.add_proof(second)
        store.record_reproduction(
            ReproductionAttempt(
                attempt_id="RA-ISS-1#2",
                issue_id="ISS-1",
                attempt_index=store.next_reproduction_index("ISS-1"),
                status=ReproductionAttemptStatus.PROVEN,
                proof_id=second.proof_id,
            )
        )
        attempts = store.reproduction_attempts_for("ISS-1")
        self.assertEqual([item.attempt_index for item in attempts], [1, 2])
        self.assertEqual([item.attempt_id for item in attempts], ["RA-ISS-1#1", "RA-ISS-1#2"])
        self.assertEqual(store.proof_for("ISS-1").proof_id, second.proof_id)
        self.assertEqual(len(store.proofs), 1)

    def test_patch_attempts_append_while_patch_stays_latest(self) -> None:
        store = MemoryStore()
        make_issue(store, "ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        for suffix in ("1", "2"):
            store.add_patch(make_patch("ISS-1", suffix))
            store.record_patch(
                PatchAttempt(
                    attempt_id=f"PA-ISS-1#{suffix}",
                    issue_id="ISS-1",
                    attempt_index=store.next_patch_index("ISS-1"),
                    patch_id=f"PA-ISS-1-{suffix}",
                )
            )
        self.assertEqual([item.attempt_id for item in store.patch_attempts_for("ISS-1")], ["PA-ISS-1#1", "PA-ISS-1#2"])
        self.assertEqual(store.patch_for("ISS-1").patch_id, "PA-ISS-1-2")
        self.assertEqual(len(store.patches), 1)

    def test_duplicate_attempt_id_is_rejected(self) -> None:
        store = MemoryStore()
        store.record_reproduction(
            ReproductionAttempt(
                attempt_id="RA-ISS-1#1",
                issue_id="ISS-1",
                attempt_index=1,
                status=ReproductionAttemptStatus.PROVEN,
            )
        )
        with self.assertRaises(AppendOnlyViolation):
            store.record_reproduction(
                ReproductionAttempt(
                    attempt_id="RA-ISS-1#1",
                    issue_id="ISS-1",
                    attempt_index=2,
                    status=ReproductionAttemptStatus.REPRO_FAILED,
                )
            )

    def test_gate_attempts_append_per_patch(self) -> None:
        store = MemoryStore()
        store.record_gate(GateAttempt(attempt_id="GA-PA-ISS-1#1", patch_id="PA-ISS-1", issue_id="ISS-1"))
        store.record_gate(
            GateAttempt(
                attempt_id="GA-PA-ISS-1#2",
                patch_id="PA-ISS-1",
                issue_id="ISS-1",
                outcome=GateOutcome.FAILED,
            )
        )
        attempts = store.gate_attempts_for("PA-ISS-1")
        self.assertEqual([item.attempt_id for item in attempts], ["GA-PA-ISS-1#1", "GA-PA-ISS-1#2"])


class AgentAttemptProbeTest(unittest.TestCase):
    def setUp(self) -> None:
        self.config = load_config()
        self.store = MemoryStore()
        self.repo = LocalRepoAdapter()
        self.repo.load_from_directory(TARGET)
        self.reachability = ReachabilityService(self.store, self.config)
        self.reproducer = ReproducerService(self.store, LocalTestExecutor(), self.config)
        self.patcher = PatcherService(self.store, self.config)
        self.critic = CriticService(self.store, self.config, LocalTestExecutor())
        self.pipeline = RecordedPipelineClient.all_passed()
        self.gatekeeper = GatekeeperService(self.store, self.config, self.repo, self.pipeline)

    def prepare(self, issue_id: str, defect: DefectClass, file: str, line: int, rule_id: str):
        make_issue(self.store, issue_id, defect, file, line, rule_id)
        self.reachability.analyze(self.store.get(issue_id), TARGET)
        repro = self.reproducer.reproduce(self.store.get(issue_id), TARGET)
        self.assertEqual(repro.status.value, "PROVEN", repro.message)
        patch_outcome = self.patcher.patch(self.store.get(issue_id), TARGET)
        self.assertEqual(patch_outcome.status, "PATCHED", patch_outcome.message)
        return self.store.get(issue_id), patch_outcome.patch, repro.proof, patch_outcome.candidate

    def test_reproducer_appends_attempt_with_proof(self) -> None:
        make_issue(self.store, "ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        self.reachability.analyze(self.store.get("ISS-1"), TARGET)
        repro = self.reproducer.reproduce(self.store.get("ISS-1"), TARGET)
        self.assertEqual(repro.status.value, "PROVEN", repro.message)
        attempts = self.store.reproduction_attempts_for("ISS-1")
        self.assertEqual(len(attempts), 1)
        self.assertEqual(attempts[0].attempt_index, 1)
        self.assertIs(attempts[0].status, ReproductionAttemptStatus.PROVEN)
        self.assertEqual(attempts[0].proof_id, repro.proof.proof_id)

    def test_patcher_appends_attempt_with_index(self) -> None:
        issue, patch, proof, candidate = self.prepare("ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        attempts = self.store.patch_attempts_for("ISS-1")
        self.assertEqual(len(attempts), 1)
        self.assertEqual(attempts[0].attempt_id, "PA-ISS-1#1")
        self.assertEqual(attempts[0].attempt_index, 1)
        self.assertEqual(attempts[0].patch_id, patch.patch_id)

    def test_l1_sets_ready_at_and_disposition_history(self) -> None:
        issue, patch, proof, candidate = self.prepare("ISS-4", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        critic = self.critic.evaluate(issue, patch, candidate, TARGET)
        outcome = self.gatekeeper.dispose(issue, patch, proof, candidate, critic, "run-4")
        self.assertEqual(outcome.status, "L1", outcome.message)
        disposition = self.store.disposition_for("ISS-4")
        self.assertIsNotNone(disposition.ready_at)
        self.assertEqual(disposition.ready_at.tzinfo, timezone.utc)
        self.assertGreaterEqual(disposition.ready_at, disposition.decided_at - timedelta(seconds=1))
        attempts = self.store.gate_attempts_for(patch.patch_id)
        self.assertEqual(len(attempts), 1)
        self.assertIs(attempts[0].outcome, GateOutcome.PASSED)
        history = self.store.disposition_history_for("ISS-4")
        self.assertEqual(len(history), 1)
        self.assertEqual(history[0].attempt_id, self.store.patch_attempts_for("ISS-4")[0].attempt_id)
        self.assertEqual(history[0].ready_at, disposition.ready_at)

    def test_l2_rollback_keeps_ready_at_none(self) -> None:
        issue, patch, proof, candidate = self.prepare("ISS-6", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        self.pipeline.stages["regression"] = GateStageResult("regression", True, coverage_delta_pp=-0.9)
        critic = self.critic.evaluate(issue, patch, candidate, TARGET)
        outcome = self.gatekeeper.dispose(issue, patch, proof, candidate, critic, "run-6")
        self.assertEqual(outcome.status, "L2", outcome.message)
        disposition = self.store.disposition_for("ISS-6")
        self.assertIsNone(disposition.ready_at)
        attempts = self.store.gate_attempts_for(patch.patch_id)
        self.assertEqual(len(attempts), 1)
        self.assertIs(attempts[0].outcome, GateOutcome.FAILED)
        history = self.store.disposition_history_for("ISS-6")
        self.assertEqual(len(history), 1)
        self.assertIsNone(history[0].ready_at)

    def test_gate_timeout_records_not_executed_attempt(self) -> None:
        issue, patch, proof, candidate = self.prepare("ISS-7", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        self.pipeline.timeout = True
        critic = self.critic.evaluate(issue, patch, candidate, TARGET)
        outcome = self.gatekeeper.dispose(issue, patch, proof, candidate, critic, "run-7")
        self.assertEqual(outcome.status, "L2", outcome.message)
        attempts = self.store.gate_attempts_for(patch.patch_id)
        self.assertEqual(len(attempts), 1)
        self.assertIs(attempts[0].outcome, GateOutcome.NOT_EXECUTED)
        self.assertTrue(attempts[0].evidence_missing)


class ComponentCounterExampleTest(unittest.TestCase):
    def test_latest_patch_without_history_has_no_first_attempt(self) -> None:
        store = MemoryStore()
        store.add_patch(make_patch("ISS-1"))
        self.assertIsNotNone(store.patch_for("ISS-1"))
        self.assertEqual(store.patch_attempts_for("ISS-1"), [])

    def test_gap_in_attempt_index_is_representable(self) -> None:
        store = MemoryStore()
        store.record_patch(
            PatchAttempt(attempt_id="PA-ISS-1#2", issue_id="ISS-1", attempt_index=2, patch_id="PA-ISS-1")
        )
        self.assertEqual([item.attempt_index for item in store.patch_attempts_for("ISS-1")], [2])

    def test_all_dispositions_missing_ready_at(self) -> None:
        store = MemoryStore()
        store.record_disposition(DispositionHistoryEntry(issue_id="ISS-1", level=DispositionLevel.L1))
        store.record_disposition(DispositionHistoryEntry(issue_id="ISS-2", level=DispositionLevel.L1))
        for issue_id in ("ISS-1", "ISS-2"):
            self.assertTrue(all(item.ready_at is None for item in store.disposition_history_for(issue_id)))

    def test_ready_at_before_first_observed_at_is_preserved_for_rule_layer(self) -> None:
        store = MemoryStore()
        observed_at = datetime(2026, 12, 10, 12, 0, tzinfo=timezone.utc)
        alert = Alert(
            alert_ref="check:ISS-1",
            source_kind=SourceKind.CHECK,
            rule_id="py/sql-injection",
            location=Location(file="app/main.py", line=31),
            raw_severity=Severity.HIGH,
            snippet_fingerprint="s" * 64,
            defect_class=DefectClass.SQL_INJECTION,
            observed_at=observed_at,
        )
        store.link_alert("ISS-1", alert)
        store.record_disposition(
            DispositionHistoryEntry(
                issue_id="ISS-1",
                level=DispositionLevel.L1,
                ready_at=observed_at - timedelta(hours=1),
            )
        )
        self.assertLess(store.disposition_history_for("ISS-1")[0].ready_at, store.alerts_for("ISS-1")[0].observed_at)


