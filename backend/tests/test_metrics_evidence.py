def make_issue(store: MemoryStore, issue_id: str, defect: DefectClass, file: str, line: int, rule_id: str) -> Issue:
    issue = Issue(
        issue_id=issue_id,
        repo="verifix-target",
        code_version="abc123",
        defect_class=defect,
        severity=Severity.HIGH,
        status=IssueStatus.RECEIVED,
        fingerprint=("f" * 63) + issue_id[-1],
    )
    store.add(issue)
    store.link_alert(
        issue_id,
        Alert(
            alert_ref=f"check:{issue_id}",
            source_kind=SourceKind.CHECK,
            rule_id=rule_id,
            location=Location(file=file, line=line),
            raw_severity=Severity.HIGH,
            snippet_fingerprint="s" * 64,
            defect_class=defect,
        ),
    )
    return issue


def make_proof(issue_id: str, suffix: str = "1") -> Proof:
    return Proof(
        proof_id=f"P-{issue_id}-{suffix}",
        issue_id=issue_id,
        test_path=f"tests/security/test_{suffix}.py",
        pre_patch_result=__import__("app.domain.enums", fromlist=["ProofResult"]).ProofResult.FAIL,
        fingerprint=("a" * 63) + suffix[-1],
        env_snapshot=EnvSnapshot(),
        generated_marker="AUTOGENERATED",
    )


def make_patch(issue_id: str, suffix: str = "1") -> Patch:
    return Patch(
        patch_id=f"PA-{issue_id}-{suffix}",
        issue_id=issue_id,
        proof_id=f"P-{issue_id}-{suffix}",
        branch=f"verifix/{issue_id}",
        diff_ref=f"sha256:{suffix}",
        lines_changed=2,
        files_changed=1,
        fix_paradigm=FixParadigm.PARAMETERIZED_QUERY,
        patch_strength=0.8,
    )


