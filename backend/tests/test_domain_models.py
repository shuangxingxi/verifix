def issue(status: IssueStatus = IssueStatus.RECEIVED) -> Issue:
    return Issue(
        issue_id="ISS-001",
        repo="verifix-target",
        code_version="abc123",
        defect_class=DefectClass.SQL_INJECTION,
        severity=Severity.HIGH,
        status=status,
        fingerprint="f" * 64,
        source_count=2,
    )


class DomainModelTest(unittest.TestCase):
    def test_issue_requires_defect_class_when_in_scope(self) -> None:
        with self.assertRaises(ValidationError):
            Issue(
                issue_id="ISS-002",
                repo="demo",
                code_version="v1",
                severity=Severity.HIGH,
                fingerprint="a" * 64,
            )

    def test_out_of_scope_issue_allows_missing_class(self) -> None:
        out_of_scope = Issue(
            issue_id="ISS-003",
            repo="demo",
            code_version="v1",
            severity=Severity.LOW,
            fingerprint="b" * 64,
            in_scope=False,
        )
        self.assertIsNone(out_of_scope.defect_class)

    def test_location_requires_line_or_component(self) -> None:
        Location(file="app/user.py", line=42)
        Location(file="requirements.txt", component="flask", component_version="2.0.1")
        with self.assertRaises(ValidationError):
            Location(file="app/user.py")

    def test_verdict_reachable_requires_taint_path(self) -> None:
        with self.assertRaises(ValidationError):
            Verdict(
                verdict_id="V-1",
                issue_id="ISS-001",
                conclusion="REACHABLE",
                confidence=0.9,
                decided_by="tracer",
            )

    def test_verdict_unreachable_requires_basis(self) -> None:
        with self.assertRaises(ValidationError):
            Verdict(
                verdict_id="V-2",
                issue_id="ISS-001",
                conclusion="UNREACHABLE",
                confidence=0.9,
                decided_by="tracer",
            )

    def test_proof_pre_patch_must_fail(self) -> None:
        with self.assertRaises(ValidationError):
            Proof(
                proof_id="P-1",
                issue_id="ISS-001",
                test_path="tests/security/test_iss_001.py",
                pre_patch_result=ProofResult.PASS,
                fingerprint="c" * 64,
                env_snapshot=EnvSnapshot(),
                generated_marker="AUTOGENERATED",
            )
        proof = Proof(
            proof_id="P-2",
            issue_id="ISS-001",
            test_path="tests/security/test_iss_001.py",
            pre_patch_result=ProofResult.FAIL,
            fingerprint="c" * 64,
            env_snapshot=EnvSnapshot(),
            generated_marker="AUTOGENERATED",
        )
        self.assertIs(proof.pre_patch_result, ProofResult.FAIL)

    def test_patch_branch_namespace_enforced(self) -> None:
        with self.assertRaises(ValidationError):
            Patch(
                patch_id="PA-1",
                issue_id="ISS-001",
                proof_id="P-2",
                branch="hotfix/x",
                diff_ref="obs://diff/1",
                lines_changed=2,
                files_changed=1,
                fix_paradigm=FixParadigm.PARAMETERIZED_QUERY,
                patch_strength=0.9,
            )

    def test_disposition_l0_l1_requires_passed_gate(self) -> None:
        with self.assertRaises(ValidationError):
            Disposition(
                disposition_id="D-1",
                issue_id="ISS-001",
                level=DispositionLevel.L1,
                action="open_pr",
                evidence_ref="obs://evidence/1",
                reason_code="AUDIT_OK",
            )
        disposition = Disposition(
            disposition_id="D-2",
            issue_id="ISS-001",
            level=DispositionLevel.L1,
            action="open_pr",
            evidence_ref="obs://evidence/1",
            reason_code="AUDIT_OK",
            gate_outcome=GateOutcome.PASSED,
        )
        self.assertIs(disposition.level, DispositionLevel.L1)

    def test_disposition_requires_evidence_ref(self) -> None:
        with self.assertRaises(ValidationError):
            Disposition(
                disposition_id="D-3",
                issue_id="ISS-001",
                level=DispositionLevel.L2,
                action="report_only",
                evidence_ref="",
                reason_code="WEAK_PATCH",
            )

    def test_metric_computable_requires_value(self) -> None:
        with self.assertRaises(ValidationError):
            Metric(
                metric_id=MetricId.M4,
                stage_tier=StageTier.PRELIMINARY,
                window="2026-12",
                definition_version="v1",
                source_ref="verdict",
            )
        metric = Metric(
            metric_id=MetricId.M4,
            stage_tier=StageTier.PRELIMINARY,
            window="2026-12",
            definition_version="v1",
            value=0.72,
            source_ref="verdict",
        )
        self.assertAlmostEqual(metric.value or 0, 0.72)

    def test_positive_eval_case_requires_proof_expectation(self) -> None:
        with self.assertRaises(ValidationError):
            EvalCase(
                case_id="EVAL-0001",
                category=EvalCategory.POSITIVE,
                location=Location(file="app/user.py", line=42),
                rule_id="py/sql-injection",
                severity=Severity.HIGH,
                ground_truth=GroundTruth(
                    reachable=True,
                    fixable=True,
                    expected_fix_kind=FixParadigm.PARAMETERIZED_QUERY,
                    should_reject=False,
                ),
                content_digest="d" * 64,
            )

    def test_alert_records_source_and_location(self) -> None:
        alert = Alert(
            alert_ref="check:task-1:rule-1",
            source_kind=SourceKind.CHECK,
            rule_id="py/sql-injection",
            location=Location(file="app/user.py", line=42),
            raw_severity=Severity.HIGH,
            snippet_fingerprint="e" * 64,
        )
        self.assertIs(alert.source_kind, SourceKind.CHECK)

    def test_audit_finding_keeps_rule_and_threshold(self) -> None:
        finding = AuditFinding(
            patch_id="PA-1",
            rule_id=AuditRuleId.R2,
            threshold="no new branch",
            hit_location="app/user.py:42",
            verdict=AuditVerdict.REJECT,
            reason="added conditional",
        )
        self.assertIs(finding.verdict, AuditVerdict.REJECT)


if __name__ == "__main__":
    unittest.main()