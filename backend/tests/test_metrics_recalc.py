class RecalcIdTest(unittest.TestCase):
    def test_ids_unique_and_enums_fixed(self) -> None:
        ids = {new_recalc_id(NOW) for _ in range(50)}
        self.assertEqual(len(ids), 50)
        self.assertTrue(all(item.startswith("RC-") for item in ids))
        self.assertEqual({item.value for item in RecalcTrigger}, {"MANUAL", "DASHBOARD", "SCHEDULED"})
        self.assertEqual({item.value for item in RecalcStatus}, {"RUNNING", "SUCCESS", "FAILED"})


class RecalcServiceTest(RecalcFixture):
    def test_full_recalc_success(self) -> None:
        result = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        self.assertTrue(result.succeeded)
        self.assertEqual(len(result.computations), 9)
        records = self.store.metrics_for("2026-12", StageTier.PRELIMINARY)
        self.assertEqual(len(records), 9)
        by_id = {record.metric_id: record for record in records}
        self.assertAlmostEqual(by_id[MetricId.M4].value, 1.0)
        self.assertAlmostEqual(by_id[MetricId.M5].value, 1.0)
        self.assertAlmostEqual(by_id[MetricId.M6].value, 0.0)
        self.assertAlmostEqual(by_id[MetricId.M7].value, 30.0)
        self.assertAlmostEqual(by_id[MetricId.M8].value, 1.0)
        self.assertTrue(by_id[MetricId.M1].computable)
        self.assertFalse(by_id[MetricId.M2].computable)
        self.assertEqual(by_id[MetricId.M2].reason_code, "SOURCE_MISSING")
        self.assertAlmostEqual(by_id[MetricId.M9].value, 24.0)
        for record in records:
            self.assertIsNotNone(record.recalc_id)
            self.assertIsNotNone(record.snapshot_digest)
            self.assertEqual(record.definition_version, "v2")
        run = self.store.get_recalc(result.recalc_id)
        self.assertEqual(run.status, "SUCCESS")
        self.assertEqual(run.trigger, "MANUAL")
        self.assertEqual(run.actor, "tester")
        self.assertEqual(run.issue_total, 1)

    def test_p11_second_recalc_still_nine_records(self) -> None:
        first = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester", now=NOW)
        second = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester", now=NOW)
        self.assertNotEqual(first.recalc_id, second.recalc_id)
        records = self.store.metrics_for("2026-12", StageTier.PRELIMINARY)
        self.assertEqual(len(records), 9)
        self.assertTrue(all(record.recalc_id == second.recalc_id for record in records))

    def test_p10_same_snapshot_is_deterministic(self) -> None:
        first = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester", now=NOW)
        first_values = {metric_id: item.value for metric_id, item in first.computations.items()}
        second = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester", now=NOW)
        second_values = {metric_id: item.value for metric_id, item in second.computations.items()}
        self.assertEqual(first_values, second_values)
        self.assertEqual(first.snapshot.digest, second.snapshot.digest)

    def test_dashboard_and_scheduled_share_service(self) -> None:
        dashboard = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.DASHBOARD, "ui")
        scheduled = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.SCHEDULED, "scheduler:metrics")
        self.assertEqual(self.store.get_recalc(dashboard.recalc_id).trigger, "DASHBOARD")
        self.assertEqual(self.store.get_recalc(scheduled.recalc_id).trigger, "SCHEDULED")

    def test_n19_concurrent_request_rejected_without_writes(self) -> None:
        with self.guard.acquire("2026-12", StageTier.PRELIMINARY, "RC-ACTIVE"):
            before = len(self.store.recalc_runs)
            with self.assertRaises(RecalcConflict):
                self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
            self.assertEqual(len(self.store.recalc_runs), before)
            self.assertEqual(len(self.store.metrics), 0)

    def test_n22_missing_definition_fails_whole_run(self) -> None:
        partial = DefinitionRegistry([])
        for definition in default_definitions():
            if definition.metric_id is MetricId.M6:
                continue
            partial.register(definition)
        service = RecalcService(
            self.store,
            self.evidence,
            self.config,
            definitions=partial,
            guard=self.guard,
            collector=MainFlowEvidenceCollector(),
            clock=lambda: NOW,
        )
        with self.assertRaises(DefinitionMissing):
            service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        self.assertEqual(len(self.store.metrics), 0)
        runs = list(self.store.recalc_runs.values())
        self.assertEqual(len(runs), 1)
        self.assertEqual(runs[0].status, "FAILED")
        self.assertIn("DEFINITION_UNREGISTERED", runs[0].failure_reason)

    def test_n15_tampered_snapshot_fails_with_zero_metric_writes(self) -> None:
        first = self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        before = {record.metric_id: record.value for record in self.store.metrics_for("2026-12")}
        path = self.root / "evidence" / "metrics" / "snapshots" / f"{first.snapshot.snapshot_id}.json"
        os.chmod(path, 0o644)
        path.write_text("{}", encoding="utf-8")
        with self.assertRaises(RecalcFailed):
            self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        after = {record.metric_id: record.value for record in self.store.metrics_for("2026-12")}
        self.assertEqual(before, after)
        self.assertEqual(len(self.store.metrics), 9)
        failed = [run for run in self.store.recalc_runs.values() if run.status == "FAILED"]
        self.assertEqual(len(failed), 1)

    def test_n18_exception_during_write_rolls_back(self) -> None:
        original = self.store.add_metric
        calls = {"n": 0}

        def boom(metric):
            calls["n"] += 1
            if calls["n"] == 3:
                raise RuntimeError("write failure")
            return original(metric)

        self.store.add_metric = boom  # type: ignore[assignment]
        with self.assertRaises(RecalcFailed):
            self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        self.store.add_metric = original  # type: ignore[assignment]
        self.assertEqual(len(self.store.metrics), 0)
        self.assertEqual(self.store.metric_exclusions, {})
        failed = [run for run in self.store.recalc_runs.values() if run.status == "FAILED"]
        self.assertEqual(len(failed), 1)

    def test_guard_released_after_failure(self) -> None:
        self.store.add_metric = lambda metric: (_ for _ in ()).throw(RuntimeError("boom"))  # type: ignore[assignment]
        with self.assertRaises(RecalcFailed):
            self.service.recalc("2026-12", StageTier.PRELIMINARY, RecalcTrigger.MANUAL, "tester")
        self.assertIsNone(self.guard.active("2026-12", StageTier.PRELIMINARY))


class SchedulerTest(RecalcFixture):
    def setUp(self) -> None:
        super().setUp()
        metrics = self.config.metrics.model_copy(update={"scheduler_enabled": True})
        self.config = self.config.model_copy(update={"metrics": metrics})
        self.service.config = self.config
        self.scheduler = RecalcScheduler(self.service, self.store, self.config, clock=lambda: NOW)

    def test_closed_window_backfill_and_late_flag(self) -> None:
        results = self.scheduler.tick(NOW)
        self.assertTrue(results)
        self.assertTrue(any(result.late for result in results))
        self.assertEqual(results[0].actor, "scheduler:metrics")
        self.assertEqual(self.store.get_recalc(results[0].recalc_id).trigger, "SCHEDULED")

    def test_same_day_not_repeated(self) -> None:
        self.scheduler.tick(NOW)
        runs = len(self.store.recalc_runs)
        self.scheduler.tick(NOW)
        self.assertEqual(len(self.store.recalc_runs), runs)

    def test_archived_window_skipped(self) -> None:
        self.store.put_report(
            MetricReport(
                report_id="RPT-1",
                window="2026-12",
                tier=StageTier.PRELIMINARY,
                definition_version="v2",
                conclusion="PASS",
            )
        )
        results = self.scheduler.tick(NOW)
        self.assertFalse(any(result.window == "2026-12" for result in results))

    def test_lock_conflict_counted(self) -> None:
        with self.guard.acquire("2026-12", StageTier.PRELIMINARY, "RC-ACTIVE"):
            self.scheduler.tick(NOW)
        self.assertGreater(self.scheduler.skipped_locked, 0)

    def test_disabled_scheduler_does_nothing(self) -> None:
        metrics = self.config.metrics.model_copy(update={"scheduler_enabled": False})
        config = self.config.model_copy(update={"metrics": metrics})
        scheduler = RecalcScheduler(self.service, self.store, config, clock=lambda: NOW)
        self.assertEqual(scheduler.tick(NOW), [])


