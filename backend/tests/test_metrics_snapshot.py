class WindowAnnotationTest(SnapshotFixture):
    def test_window_bounds(self) -> None:
        start, end = window_bounds("2026-12")
        self.assertEqual(start, datetime(2026, 12, 1, tzinfo=timezone.utc))
        self.assertEqual(end, datetime(2027, 1, 1, tzinfo=timezone.utc))
        with self.assertRaises(ValueError):
            window_bounds("2026-13")

    def test_boundary_ownership_and_naive_marking(self) -> None:
        self.store.add(make_issue("ISS-1"))
        self.store.add(make_issue("ISS-2"))
        self.store.add(make_issue("ISS-3"))
        self.store.add(make_issue("ISS-4"))
        self.store.link_alert("ISS-1", make_alert("ISS-1", datetime(2026, 12, 1, tzinfo=timezone.utc)))
        self.store.link_alert("ISS-2", make_alert("ISS-2", datetime(2026, 11, 30, 23, 59, 59, tzinfo=timezone.utc)))
        self.store.link_alert("ISS-3", make_alert("ISS-3", datetime(2027, 1, 1, tzinfo=timezone.utc)))
        self.store.link_alert("ISS-4", make_alert("ISS-4", datetime(2026, 12, 20, 8, 0)))
        envelope = self.build()
        annotations = envelope.payload["annotations"]
        self.assertTrue(annotations["ISS-1"]["window_owner"])
        self.assertFalse(annotations["ISS-2"]["window_owner"])
        self.assertFalse(annotations["ISS-3"]["window_owner"])
        self.assertTrue(annotations["ISS-4"]["window_owner"])
        self.assertTrue(annotations["ISS-4"]["tz_unavailable"])
        self.assertFalse(annotations["ISS-1"]["fallback_occurred_at"])

    def test_naive_time_is_marked(self) -> None:
        value, ok = annotate_time(datetime(2026, 12, 1))
        self.assertFalse(ok)
        self.assertIsNotNone(value.tzinfo)
        self.assertIsNone(annotate_time(None)[0])


