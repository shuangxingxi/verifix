def make_issue(issue_id: str, status: IssueStatus = IssueStatus.RECEIVED) -> Issue:
    return Issue(
        issue_id=issue_id,
        repo="verifix-target",
        code_version="abc123",
        defect_class=DefectClass.SQL_INJECTION,
        severity=Severity.HIGH,
        status=status,
        fingerprint=("f" * 63) + issue_id[-1],
    )


def make_alert(issue_id: str, observed_at: datetime, snippet: str = "c.execute(query)") -> Alert:
    return Alert(
        alert_ref=f"check:{issue_id}",
        source_kind=SourceKind.CHECK,
        rule_id="py/sql-injection",
        location=Location(file="app/main.py", line=31),
        raw_severity=Severity.HIGH,
        snippet_fingerprint="s" * 64,
        defect_class=DefectClass.SQL_INJECTION,
        snippet=snippet,
        observed_at=observed_at,
    )


class SnapshotFixture(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.evidence = LocalEvidenceStore(Path(self.tmp.name))
        self.store = MemoryStore()

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def build(self, window: str = "2026-12", tier: StageTier = StageTier.PRELIMINARY):
        return SnapshotBuilder(self.store, self.evidence).capture(window, tier)


class DigestTest(SnapshotFixture):
    def test_snapshot_digest_stable_content_digest_sensitive(self) -> None:
        self.store.add(make_issue("ISS-1"))
        before_snapshot = self.store.snapshot_digest()
        before_content = self.store.content_digest()
        self.store.update(make_issue("ISS-1", IssueStatus.PROVEN))
        self.assertEqual(self.store.snapshot_digest(), before_snapshot)
        self.assertNotEqual(self.store.content_digest(), before_content)

    def test_capture_is_deterministic_and_reuses_archive(self) -> None:
        self.store.add(make_issue("ISS-1"))
        self.store.link_alert("ISS-1", make_alert("ISS-1", datetime(2026, 12, 5, tzinfo=timezone.utc)))
        first = self.build()
        second = self.build()
        self.assertEqual(first.ref.digest, second.ref.digest)
        self.assertEqual(first.ref.snapshot_id, second.ref.snapshot_id)
        self.assertTrue(second.reused)
        self.assertGreaterEqual(first.ref.capture_ms, 0)
        self.assertTrue(first.ref.chain_valid)
        self.assertEqual(first.ref.issue_count, 1)

    def test_redaction_removes_secret_and_keeps_digest(self) -> None:
        self.store.add(make_issue("ISS-1"))
        self.store.link_alert(
            "ISS-1",
            make_alert("ISS-1", datetime(2026, 12, 5, tzinfo=timezone.utc), snippet="key=AKIAABCDEFGHIJKLMNOP"),
        )
        envelope = self.build()
        self.assertGreater(envelope.ref.redaction_hits, 0)
        serialized = json.dumps(envelope.payload, ensure_ascii=False)
        self.assertNotIn("AKIAABCDEFGHIJKLMNOP", serialized)
        self.assertIn("REDACTED", serialized)
        self.assertEqual(_digest(envelope.payload), envelope.ref.digest)

    def test_evidence_refs_are_whitelisted(self) -> None:
        proof = Proof(
            proof_id="P-ISS-1",
            issue_id="ISS-1",
            test_path="tests/security/test_sql.py",
            pre_patch_result=__import__("app.domain.enums", fromlist=["ProofResult"]).ProofResult.FAIL,
            fingerprint="a" * 64,
            env_snapshot=EnvSnapshot(),
            generated_marker="AUTOGENERATED",
        )
        patch = Patch(
            patch_id="PA-ISS-1",
            issue_id="ISS-1",
            proof_id="P-ISS-1",
            branch="verifix/ISS-1",
            diff_ref="sha256:" + "b" * 64,
            lines_changed=1,
            files_changed=1,
            fix_paradigm=__import__("app.domain.enums", fromlist=["FixParadigm"]).FixParadigm.PARAMETERIZED_QUERY,
            patch_strength=0.8,
        )
        self.store.add(make_issue("ISS-1"))
        self.store.link_alert("ISS-1", make_alert("ISS-1", datetime(2026, 12, 5, tzinfo=timezone.utc)))
        self.store.add_proof(proof)
        self.store.add_patch(patch)
        envelope = self.build()
        self.assertEqual(envelope.payload["patches"]["ISS-1"]["diff_ref"], "sha256:" + "b" * 64)
        self.assertEqual(envelope.payload["proofs"]["ISS-1"]["fingerprint"], "a" * 64)
        self.assertEqual(envelope.payload["patches"]["ISS-1"]["branch"], "verifix/ISS-1")


class VerifierTest(SnapshotFixture):
    def test_n15_tampered_archive_digest_mismatch(self) -> None:
        self.store.add(make_issue("ISS-1"))
        self.store.link_alert("ISS-1", make_alert("ISS-1", datetime(2026, 12, 5, tzinfo=timezone.utc)))
        envelope = self.build()
        key = f"metrics/snapshots/{envelope.ref.snapshot_id}.json"
        path = Path(self.tmp.name) / key
        os.chmod(path, 0o644)
        data = json.loads(path.read_text(encoding="utf-8"))
        data["window"] = "2026-11"
        path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        report = SnapshotVerifier(self.evidence).verify(envelope.ref.snapshot_id, envelope.ref.digest)
        self.assertFalse(report.digest_match)

    def test_n16_tampered_event_breaks_chain(self) -> None:
        self.store.add(make_issue("ISS-1"))
        self.store.link_alert("ISS-1", make_alert("ISS-1", datetime(2026, 12, 5, tzinfo=timezone.utc)))
        self.store.add_run(
            __import__("app.domain.models", fromlist=["Run"]).Run(
                run_id="RUN-ISS-1",
                issue_id="ISS-1",
                deadline_at=datetime(2026, 12, 5, tzinfo=timezone.utc) + timedelta(seconds=900),
            )
        )
        from app.domain.enums import EventType

        self.store.append(
            __import__("app.domain.models", fromlist=["Event"]).Event(
                event_id="E-1", run_id="RUN-ISS-1", seq=1, event_type=EventType.INGEST, actor="normalizer"
            )
        )
        envelope = self.build()
        self.assertTrue(envelope.ref.chain_valid)
        data = json.loads(json.dumps(envelope.payload))
        data["events"]["RUN-ISS-1"][0]["actor"] = "tampered"
        new_digest = _digest(data)
        key = f"metrics/snapshots/{envelope.ref.snapshot_id}.json"
        path = Path(self.tmp.name) / key
        os.chmod(path, 0o644)
        path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        report = SnapshotVerifier(self.evidence).verify(envelope.ref.snapshot_id, new_digest)
        self.assertTrue(report.digest_match)
        self.assertFalse(report.chain_valid)
        self.assertEqual(report.broken_runs, ["RUN-ISS-1"])


