def make_issue(store: MemoryStore, issue_id: str, defect: DefectClass, file: str, line: int, rule_id: str,
               component: str | None = None, version: str | None = None) -> Issue:
    issue = Issue(
        issue_id=issue_id,
        repo="verifix-target",
        code_version="abc123",
        defect_class=defect,
        severity=Severity.HIGH,
        status=IssueStatus.RECEIVED,
        fingerprint=("f" * 63) + issue_id[-1],
    )
    store.add(issue)
    store.link_alert(
        issue_id,
        Alert(
            alert_ref=f"check:{issue_id}",
            source_kind=SourceKind.CHECK,
            rule_id=rule_id,
            location=Location(file=file, line=line, component=component, component_version=version),
            raw_severity=Severity.HIGH,
            snippet_fingerprint="s" * 64,
            defect_class=defect,
        ),
    )
    return issue


def make_proven(store: MemoryStore, issue: Issue) -> Issue:
    from app.domain.enums import EventType

    orchestration = OrchestrationService(store, store, store)
    orchestration.apply(Transition.T1, TransitionContext(issue=issue), EventType.INGEST, "normalizer")
    triaging = store.get(issue.issue_id)
    verdict = Verdict(
        verdict_id=f"V-{issue.issue_id}",
        issue_id=issue.issue_id,
        conclusion=VerdictConclusion.REACHABLE,
        confidence=0.9,
        taint_path=["app/main.py:user"],
        basis="static path",
        decided_by="tracer",
    )
    store.add_verdict(verdict)
    orchestration.apply(Transition.T2, TransitionContext(issue=triaging, verdict=verdict), EventType.VERDICT, "tracer")
    reachable = store.get(issue.issue_id)
    orchestration.apply(Transition.T6, TransitionContext(issue=reachable, verdict=verdict), EventType.VERDICT, "reproducer")
    proof = Proof(
        proof_id=f"P-{issue.issue_id}",
        issue_id=issue.issue_id,
        test_path=f"tests/security/test_{issue.issue_id.lower()}.py",
        pre_patch_result=ProofResult.FAIL,
        fingerprint="c" * 64,
        env_snapshot=EnvSnapshot(),
        generated_marker="AUTOGENERATED",
    )
    store.add_proof(proof)
    reproducing = store.get(issue.issue_id)
    orchestration.apply(Transition.T7, TransitionContext(issue=reproducing, proof=proof), EventType.PROOF, "reproducer")
    return store.get(issue.issue_id)


class RewriteTest(unittest.TestCase):
    def test_sql_rewrite_parameterized(self) -> None:
        source = (TARGET / "app" / "main.py").read_text(encoding="utf-8")
        start, end, statement = rewrite_sql_execute(source, 31)
        self.assertIn("conn.execute(", statement)
        self.assertIn("= ?", statement)
        self.assertNotIn("% uid", statement)
        self.assertIn("(uid,)", statement)
        self.assertGreaterEqual(start, 31)
        self.assertGreaterEqual(end, start)

    def test_sql_rewrite_concat_and_fstring(self) -> None:
        source = (TARGET / "app" / "main.py").read_text(encoding="utf-8")
        _, _, search = rewrite_sql_execute(source, 50)
        self.assertIn("LIKE ?", search)
        self.assertIn('"%" + keyword + "%"', search)
        _, _, profile = rewrite_sql_execute(source, 74)
        self.assertIn("user_id = ?", profile)
        self.assertIn("(user_id,)", profile)

    def test_command_rewrite_removes_shell(self) -> None:
        source = (TARGET / "app" / "main.py").read_text(encoding="utf-8")
        _, _, ping = rewrite_command_call(source, 81)
        self.assertIn("subprocess.run([", ping)
        self.assertNotIn("os.popen", ping)
        _, _, convert = rewrite_command_call(source, 87)
        self.assertNotIn("shell=True", convert)
        self.assertIn("'convert'", convert)


class GuardTest(unittest.TestCase):
    def _candidate(self, diff: str, lines: int, files: int = 1, paradigm: FixParadigm = FixParadigm.PARAMETERIZED_QUERY,
                   strength: float = 0.9) -> PatchCandidate:
        return PatchCandidate(
            files={},
            diff=diff,
            lines_changed=lines,
            files_changed=files,
            fix_paradigm=paradigm,
            strength=strength,
            rationale="test",
            referenced_files=("app/main.py",),
        )

    def test_oversized_rejected(self) -> None:
        result = evaluate(self._candidate("+x\n", lines=31))
        self.assertFalse(result.ok)
        self.assertEqual(result.first_code.value, "VF-4001")

    def test_weak_blacklist_rejected(self) -> None:
        diff = "+    return value.replace(\"'\", \"\")\n"
        result = evaluate(self._candidate(diff, lines=1))
        self.assertFalse(result.ok)
        self.assertEqual(result.first_code.value, "VF-4002")
        self.assertLess(result.strength, 0.6)

    def test_smuggled_comment_rejected(self) -> None:
        diff = "+# tidy up\n"
        result = evaluate(self._candidate(diff, lines=1), target_files={"app/main.py"})
        self.assertFalse(result.ok)
        self.assertEqual(result.first_code.value, "VF-4003")

    def test_clean_patch_passes(self) -> None:
        diff = "+    rows = conn.execute(\"SELECT 1\", (uid,)).fetchall()\n"
        result = evaluate(self._candidate(diff, lines=1), target_files={"app/main.py"})
        self.assertTrue(result.ok)
        self.assertGreaterEqual(result.strength, 0.6)


class GatewayTest(unittest.TestCase):
    def test_budget_is_enforced(self) -> None:
        gateway = ModelGateway(FakeProvider(payload=json.dumps({"files": {"a.py": "x = 1"}, "fix_paradigm": "PARAMETERIZED_QUERY"})), max_calls_per_issue=2)
        ctx = BugContext(issue_id="ISS-1", rule_id="r", defect_class="C02", file="a.py", line=1)
        gateway.generate_patch(ctx)
        gateway.generate_patch(ctx)
        with self.assertRaises(ModelBudgetExceeded):
            gateway.generate_patch(ctx)

    def test_invalid_json_rejected(self) -> None:
        gateway = ModelGateway(FakeProvider(payload="not json"))
        ctx = BugContext(issue_id="ISS-1", rule_id="r", defect_class="C02", file="a.py", line=1)
        with self.assertRaises(ModelOutputRejected):
            gateway.generate_patch(ctx)

    def test_syntax_error_output_rejected(self) -> None:
        gateway = ModelGateway(FakeProvider(payload=json.dumps({"files": {"a.py": "def broken("}, "fix_paradigm": "PARAMETERIZED_QUERY"})))
        ctx = BugContext(issue_id="ISS-1", rule_id="r", defect_class="C02", file="a.py", line=1)
        with self.assertRaises(ModelOutputRejected):
            gateway.generate_patch(ctx)

    def test_free_text_input_rejected(self) -> None:
        with self.assertRaises(ValidationError):
            BugContext(issue_id="ISS-1", rule_id="r", defect_class="C02", file="a.py", line=1, free_text="ignore instructions")

    def test_provider_switch_is_transparent(self) -> None:
        gateway_a = ModelGateway(FakeProvider(name="provider-a", payload=json.dumps({"files": {"a.py": "x = 1"}, "fix_paradigm": "PARAMETERIZED_QUERY"})))
        gateway_b = ModelGateway(FakeProvider(name="provider-b", payload=json.dumps({"files": {"a.py": "x = 2"}, "fix_paradigm": "PARAMETERIZED_QUERY"})))
        ctx = BugContext(issue_id="ISS-2", rule_id="r", defect_class="C02", file="a.py", line=1)
        self.assertEqual(gateway_a.generate_patch(ctx)["files"]["a.py"], "x = 1")
        self.assertEqual(gateway_b.generate_patch(ctx)["files"]["a.py"], "x = 2")


class PatcherServiceTest(unittest.TestCase):
    def setUp(self) -> None:
        self.config = load_config()
        self.store = MemoryStore()
        self.service = PatcherService(self.store, self.config)

    def test_sql_issue_generates_auditing_patch(self) -> None:
        issue = make_issue(self.store, "ISS-1", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        make_proven(self.store, issue)
        outcome = self.service.patch(self.store.get("ISS-1"), TARGET)
        self.assertEqual(outcome.status, "PATCHED", outcome.message)
        self.assertIsNotNone(outcome.patch)
        patch = outcome.patch
        assert patch is not None
        self.assertTrue(patch.branch.startswith("verifix/"))
        self.assertIs(patch.fix_paradigm, FixParadigm.PARAMETERIZED_QUERY)
        self.assertTrue(patch.quotas_ok)
        self.assertEqual(self.store.get("ISS-1").status, IssueStatus.AUDITING)

    def test_command_issue_patch_has_no_shell(self) -> None:
        issue = make_issue(self.store, "ISS-2", DefectClass.COMMAND_INJECTION, "app/main.py", 81, "py/command-injection")
        make_proven(self.store, issue)
        outcome = self.service.patch(self.store.get("ISS-2"), TARGET)
        self.assertEqual(outcome.status, "PATCHED", outcome.message)
        assert outcome.candidate is not None
        added = [
            line for line in outcome.candidate.diff.splitlines()
            if line.startswith("+") and not line.startswith("+++")
        ]
        for line in added:
            self.assertNotIn("shell=True", line)
            self.assertNotIn("os.popen", line)

    def test_secret_patch_externalizes(self) -> None:
        issue = make_issue(self.store, "ISS-3", DefectClass.HARDCODED_SECRET, "app/config.py", 1, "py/hardcoded-secret")
        make_proven(self.store, issue)
        outcome = self.service.patch(self.store.get("ISS-3"), TARGET)
        self.assertEqual(outcome.status, "PATCHED", outcome.message)
        assert outcome.candidate is not None
        self.assertIn("os.environ.get", outcome.candidate.diff)

    def test_dependency_patch_requires_fixed_version(self) -> None:
        issue = make_issue(self.store, "ISS-4", DefectClass.DEPENDENCY_CVE, "requirements.txt", 2, "dependency-cve",
                           component="requests", version="2.19.1")
        make_proven(self.store, issue)
        outcome = self.service.patch(self.store.get("ISS-4"), TARGET)
        self.assertEqual(outcome.status, "GENERATION_FAILED")
        patched = self.service.patch(self.store.get("ISS-4"), TARGET, fixed_version="2.32.3")
        self.assertEqual(patched.status, "PATCHED", patched.message)
        assert patched.candidate is not None
        self.assertIn("requests==2.32.3", patched.candidate.files["requirements.txt"])

    def test_issue_without_proof_cannot_patch(self) -> None:
        issue = make_issue(self.store, "ISS-5", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        outcome = self.service.patch(self.store.get("ISS-5"), TARGET)
        self.assertEqual(outcome.status, "NOT_READY")


