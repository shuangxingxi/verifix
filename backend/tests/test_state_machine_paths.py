def make_issue(status: IssueStatus, in_scope: bool = True) -> Issue:
    return Issue(
        issue_id="ISS-200",
        repo="verifix-target",
        code_version="abc123",
        defect_class=DefectClass.SQL_INJECTION if in_scope else None,
        severity=Severity.HIGH,
        status=status,
        source_count=1,
        fingerprint="f" * 64,
        in_scope=in_scope,
    )


def make_proof(pre: ProofResult = ProofResult.FAIL) -> Proof:
    if pre is not ProofResult.FAIL:
        return Proof.model_construct(
            proof_id="P-200",
            issue_id="ISS-200",
            test_path="tests/security/test_iss_200.py",
            pre_patch_result=pre,
            post_patch_result=ProofResult.NOT_RUN,
            fingerprint="c" * 64,
            env_snapshot=EnvSnapshot(),
            generated_marker="AUTOGENERATED",
            created_at=None,
        )
    return Proof(
        proof_id="P-200",
        issue_id="ISS-200",
        test_path="tests/security/test_iss_200.py",
        pre_patch_result=pre,
        fingerprint="c" * 64,
        env_snapshot=EnvSnapshot(),
        generated_marker="AUTOGENERATED",
    )


def make_patch(
    paradigm: FixParadigm = FixParadigm.PARAMETERIZED_QUERY,
    lines: int = 4,
    files: int = 1,
    strength: float = 0.86,
    quotas_ok: bool = True,
) -> Patch:
    return Patch(
        patch_id="PA-200",
        issue_id="ISS-200",
        proof_id="P-200",
        branch="verifix/ISS-200",
        diff_ref="obs://diff/200",
        lines_changed=lines,
        files_changed=files,
        fix_paradigm=paradigm,
        patch_strength=strength,
        quotas_ok=quotas_ok,
    )


def make_gate(
    outcome: GateOutcome = GateOutcome.PASSED,
    coverage: float = -0.5,
    rescan: int = 0,
    red_green: bool | None = None,
    regression: bool | None = None,
) -> GateResult:
    return GateResult(
        gate_result_id="G-200",
        patch_id="PA-200",
        gate_run_ref="pipeline:run-200",
        red_green_paired=(outcome is GateOutcome.PASSED) if red_green is None else red_green,
        regression_zero_fail=(outcome is GateOutcome.PASSED) if regression is None else regression,
        coverage_delta_pp=coverage,
        rescan_new_alerts=rescan,
        outcome=outcome,
    )


def finding(rule: AuditRuleId = AuditRuleId.R1, verdict: AuditVerdict = AuditVerdict.PASS) -> AuditFinding:
    return AuditFinding(
        patch_id="PA-200",
        rule_id=rule,
        threshold="rule",
        hit_location="app/user.py:20",
        verdict=verdict,
    )


def verdict_reachable(confidence: float = 0.9) -> Verdict:
    return Verdict(
        verdict_id="V-200",
        issue_id="ISS-200",
        conclusion=VerdictConclusion.REACHABLE,
        confidence=confidence,
        taint_path=["request.args -> conn.execute"],
        decided_by="tracer",
    )


class TransitionRejectTest(unittest.TestCase):
    def setUp(self) -> None:
        self.sm = StateMachine()

    def _reject(self, name: str, status: IssueStatus, transition: Transition, ctx: TransitionContext, code: ErrorCode) -> None:
        with self.subTest(name=name):
            with self.assertRaises(ApiError) as raised:
                self.sm.target_status(status, transition, ctx)
            self.assertIs(raised.exception.code, code)

    def test_normalized_guards(self) -> None:
        self._reject("t1-out-of-scope", IssueStatus.RECEIVED, Transition.T1, TransitionContext(issue=make_issue(IssueStatus.RECEIVED, in_scope=False)), ErrorCode.NOT_NORMALIZED)
        self._reject("t0-out-of-scope", IssueStatus.RECEIVED, Transition.T0, TransitionContext(issue=make_issue(IssueStatus.RECEIVED, in_scope=False)), ErrorCode.NOT_NORMALIZED)

    def test_reachable_guards(self) -> None:
        status = IssueStatus.TRIAGING
        self._reject("no-verdict", status, Transition.T2, TransitionContext(issue=make_issue(status)), ErrorCode.NO_VERDICT)
        unreachable = Verdict(
            verdict_id="V-201",
            issue_id="ISS-200",
            conclusion=VerdictConclusion.UNREACHABLE,
            confidence=0.9,
            basis="no path",
            decided_by="tracer",
        )
        self._reject("not-reachable", status, Transition.T2, TransitionContext(issue=make_issue(status), verdict=unreachable), ErrorCode.NO_VERDICT)
        self._reject("low-confidence", status, Transition.T2, TransitionContext(issue=make_issue(status), verdict=verdict_reachable(0.2)), ErrorCode.NO_VERDICT)
        no_path = Verdict.model_construct(
            verdict_id="V-202",
            issue_id="ISS-200",
            conclusion=VerdictConclusion.REACHABLE,
            confidence=0.9,
            taint_path=[],
            basis="",
            decided_by="tracer",
            decided_at=make_issue(status).occurred_at,
            is_effective=True,
        )
        self._reject("no-taint-path", status, Transition.T2, TransitionContext(issue=make_issue(status), verdict=no_path), ErrorCode.NO_VERDICT)

    def test_unreachable_guards(self) -> None:
        status = IssueStatus.TRIAGING
        self._reject("no-verdict", status, Transition.T3, TransitionContext(issue=make_issue(status)), ErrorCode.NO_VERDICT)
        reachable = verdict_reachable()
        self._reject("not-unreachable", status, Transition.T3, TransitionContext(issue=make_issue(status), verdict=reachable), ErrorCode.NO_VERDICT)
        no_basis = Verdict.model_construct(
            verdict_id="V-203",
            issue_id="ISS-200",
            conclusion=VerdictConclusion.UNREACHABLE,
            confidence=0.9,
            taint_path=[],
            basis="",
            decided_by="tracer",
            decided_at=make_issue(status).occurred_at,
            is_effective=True,
        )
        self._reject("no-basis", status, Transition.T3, TransitionContext(issue=make_issue(status), verdict=no_basis), ErrorCode.NO_VERDICT)

    def test_review_and_grading_guards(self) -> None:
        self._reject("t4-no-reason", IssueStatus.TRIAGING, Transition.T4, TransitionContext(issue=make_issue(IssueStatus.TRIAGING)), ErrorCode.NO_VERDICT)
        self._reject("t5-no-actor", IssueStatus.SUSPECTED, Transition.T5, TransitionContext(issue=make_issue(IssueStatus.SUSPECTED), reason="复核"), ErrorCode.NO_VERDICT)
        self._reject("t5-no-reason", IssueStatus.SUSPECTED, Transition.T5, TransitionContext(issue=make_issue(IssueStatus.SUSPECTED), actor="lead"), ErrorCode.NO_VERDICT)
        inactive = verdict_reachable().model_copy(update={"is_effective": False})
        self._reject("t6-inactive-verdict", IssueStatus.REACHABLE, Transition.T6, TransitionContext(issue=make_issue(IssueStatus.REACHABLE), verdict=inactive), ErrorCode.NO_VERDICT)

    def test_reproduce_guards(self) -> None:
        self._reject("t7-no-proof", IssueStatus.REPRODUCING, Transition.T7, TransitionContext(issue=make_issue(IssueStatus.REPRODUCING)), ErrorCode.REPRO_FAILED)
        self._reject("t7-green", IssueStatus.REPRODUCING, Transition.T7, TransitionContext(issue=make_issue(IssueStatus.REPRODUCING), proof=make_proof(ProofResult.PASS)), ErrorCode.REPRO_FAILED)
        self._reject("t8-no-reason", IssueStatus.REPRODUCING, Transition.T8, TransitionContext(issue=make_issue(IssueStatus.REPRODUCING)), ErrorCode.REPRO_FAILED)
        self._reject("t8b-no-reason", IssueStatus.REPRO_FAILED, Transition.T8B, TransitionContext(issue=make_issue(IssueStatus.REPRO_FAILED)), ErrorCode.REPRO_FAILED)
        self._reject("t9-no-proof", IssueStatus.PROVEN, Transition.T9, TransitionContext(issue=make_issue(IssueStatus.PROVEN)), ErrorCode.REPRO_FAILED)

    def test_patch_quota_guards(self) -> None:
        status = IssueStatus.PATCHING
        cases = (
            ("no-patch", None),
            ("too-many-lines", make_patch(lines=31)),
            ("too-many-files", make_patch(files=4)),
            ("weak-strength", make_patch(strength=0.42)),
            ("quota-not-ok", make_patch(quotas_ok=False)),
        )
        for name, patch in cases:
            with self.subTest(name=name):
                with self.assertRaises(ApiError):
                    self.sm.target_status(status, Transition.T10, TransitionContext(issue=make_issue(status), proof=make_proof(), patch=patch))

    def test_audit_guards(self) -> None:
        status = IssueStatus.AUDITING
        self._reject("no-findings", status, Transition.T11, TransitionContext(issue=make_issue(status), proof=make_proof()), ErrorCode.AUDIT_HIT)
        rejected = [finding(verdict=AuditVerdict.REJECT)]
        self._reject("rejected-finding", status, Transition.T11, TransitionContext(issue=make_issue(status), proof=make_proof(), audit_findings=rejected), ErrorCode.AUDIT_HIT)
        self._reject(
            "fingerprint-mismatch",
            status,
            Transition.T11,
            TransitionContext(issue=make_issue(status), proof=make_proof(), audit_findings=[finding()], registered_test_fingerprint="d" * 64),
            ErrorCode.AUDIT_HIT,
        )
        self._reject("t12-no-reject", status, Transition.T12, TransitionContext(issue=make_issue(status), audit_findings=[finding()], patch=make_patch()), ErrorCode.AUDIT_HIT)
        self._reject("t13-no-backdoor", status, Transition.T13, TransitionContext(issue=make_issue(status), audit_findings=[finding(AuditRuleId.R1, AuditVerdict.REJECT)]), ErrorCode.BACKDOOR)

    def test_gate_guards(self) -> None:
        status = IssueStatus.GATING
        fail_cases = (
            ("gate-failed", make_gate(GateOutcome.FAILED)),
            ("red-green-missing", make_gate(red_green=False)),
            ("regression-fail", make_gate(regression=False)),
            ("coverage-over", make_gate(coverage=-0.51)),
            ("rescan-alert", make_gate(rescan=1)),
        )
        for name, gate in fail_cases:
            with self.subTest(name=name):
                with self.assertRaises(ApiError):
                    self.sm.target_status(status, Transition.T15, TransitionContext(issue=make_issue(status), patch=make_patch(), gate_result=gate))
        self._reject(
            "l0-requires-upgrade",
            status,
            Transition.T14,
            TransitionContext(issue=make_issue(status), patch=make_patch(paradigm=FixParadigm.PARAMETERIZED_QUERY), gate_result=make_gate()),
            ErrorCode.GATE_NOT_EXECUTED,
        )
        self._reject(
            "l1-requires-code-change",
            status,
            Transition.T15,
            TransitionContext(issue=make_issue(status), patch=make_patch(paradigm=FixParadigm.VERSION_UPGRADE), gate_result=make_gate()),
            ErrorCode.GATE_NOT_EXECUTED,
        )

    def test_rollback_and_review_guards(self) -> None:
        self._reject("t16-no-reason", IssueStatus.GATING, Transition.T16, TransitionContext(issue=make_issue(IssueStatus.GATING)), ErrorCode.GATE_NOT_EXECUTED)
        self._reject("t17-no-actor", IssueStatus.GATING, Transition.T17, TransitionContext(issue=make_issue(IssueStatus.GATING), reason="不可修"), ErrorCode.NO_VERDICT)
        self._reject("t18-not-deleted", IssueStatus.ROLLING_BACK, Transition.T18, TransitionContext(issue=make_issue(IssueStatus.ROLLING_BACK), branch_deleted=False), ErrorCode.GATE_NOT_EXECUTED)


class TransitionAcceptTest(unittest.TestCase):
    def setUp(self) -> None:
        self.sm = StateMachine()

    def test_accept_paths(self) -> None:
        cases = (
            (IssueStatus.RECEIVED, Transition.T1, TransitionContext(issue=make_issue(IssueStatus.RECEIVED)), IssueStatus.TRIAGING),
            (IssueStatus.TRIAGING, Transition.T2, TransitionContext(issue=make_issue(IssueStatus.TRIAGING), verdict=verdict_reachable()), IssueStatus.REACHABLE),
            (IssueStatus.TRIAGING, Transition.T4, TransitionContext(issue=make_issue(IssueStatus.TRIAGING), reason="低置信度降级"), IssueStatus.SUSPECTED),
            (IssueStatus.SUSPECTED, Transition.T5, TransitionContext(issue=make_issue(IssueStatus.SUSPECTED), actor="lead", reason="复核重判"), IssueStatus.TRIAGING),
            (IssueStatus.REACHABLE, Transition.T6, TransitionContext(issue=make_issue(IssueStatus.REACHABLE), verdict=verdict_reachable()), IssueStatus.REPRODUCING),
            (IssueStatus.REPRODUCING, Transition.T7, TransitionContext(issue=make_issue(IssueStatus.REPRODUCING), proof=make_proof()), IssueStatus.PROVEN),
            (IssueStatus.REPRODUCING, Transition.T8, TransitionContext(issue=make_issue(IssueStatus.REPRODUCING), reason="ENV_UNAVAILABLE"), IssueStatus.REPRO_FAILED),
            (IssueStatus.REPRO_FAILED, Transition.T8B, TransitionContext(issue=make_issue(IssueStatus.REPRO_FAILED), reason="二次失败"), IssueStatus.DISPOSED_L2),
            (IssueStatus.PROVEN, Transition.T9, TransitionContext(issue=make_issue(IssueStatus.PROVEN), proof=make_proof()), IssueStatus.PATCHING),
            (IssueStatus.PATCHING, Transition.T10, TransitionContext(issue=make_issue(IssueStatus.PATCHING), proof=make_proof(), patch=make_patch()), IssueStatus.AUDITING),
            (
                IssueStatus.AUDITING,
                Transition.T11,
                TransitionContext(issue=make_issue(IssueStatus.AUDITING), proof=make_proof(), audit_findings=[finding()], registered_test_fingerprint="c" * 64),
                IssueStatus.GATING,
            ),
            (
                IssueStatus.AUDITING,
                Transition.T12,
                TransitionContext(issue=make_issue(IssueStatus.AUDITING), patch=make_patch(strength=0.42), audit_findings=[finding()]),
                IssueStatus.DISPOSED_L2,
            ),
            (
                IssueStatus.AUDITING,
                Transition.T13,
                TransitionContext(issue=make_issue(IssueStatus.AUDITING), audit_findings=[finding(AuditRuleId.R2, AuditVerdict.REJECT)]),
                IssueStatus.DISPOSED_L3,
            ),
            (
                IssueStatus.GATING,
                Transition.T14,
                TransitionContext(issue=make_issue(IssueStatus.GATING), patch=make_patch(paradigm=FixParadigm.VERSION_UPGRADE), gate_result=make_gate()),
                IssueStatus.DISPOSED_L0,
            ),
            (
                IssueStatus.GATING,
                Transition.T15,
                TransitionContext(issue=make_issue(IssueStatus.GATING), patch=make_patch(), gate_result=make_gate(coverage=-0.3), coverage_tolerance_pp=0.3),
                IssueStatus.DISPOSED_L1,
            ),
            (IssueStatus.GATING, Transition.T16, TransitionContext(issue=make_issue(IssueStatus.GATING), gate_failure_reason="regression fail"), IssueStatus.ROLLING_BACK),
            (IssueStatus.SUSPECTED, Transition.T17, TransitionContext(issue=make_issue(IssueStatus.SUSPECTED), actor="lead", reason="不可修"), IssueStatus.DISPOSED_L2),
            (IssueStatus.ROLLING_BACK, Transition.T18, TransitionContext(issue=make_issue(IssueStatus.ROLLING_BACK), branch_deleted=True), IssueStatus.DISPOSED_L2),
        )
        for status, transition, ctx, expected in cases:
            with self.subTest(transition=transition.value):
                self.assertIs(self.sm.target_status(status, transition, ctx), expected)

    def test_illegal_source_state(self) -> None:
        with self.assertRaises(StateTransitionError):
            self.sm.target_status(IssueStatus.TRIAGING, Transition.T1, TransitionContext(issue=make_issue(IssueStatus.TRIAGING)))

    def test_allowed_and_disposition_mapping(self) -> None:
        allowed = self.sm.allowed(IssueStatus.TRIAGING)
        self.assertIn(Transition.T2, allowed)
        self.assertIn(Transition.T3, allowed)
        self.assertIn(Transition.T4, allowed)
        self.assertEqual(self.sm.disposition_level(IssueStatus.DISPOSED_L2).value, "L2")
        self.assertIsNone(self.sm.disposition_level(IssueStatus.TRIAGING))


