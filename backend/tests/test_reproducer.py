def make_issue(store: MemoryStore, issue_id: str, defect: DefectClass, file: str, line: int, rule_id: str) -> Issue:
    issue = Issue(
        issue_id=issue_id,
        repo="verifix-target",
        code_version="abc123",
        defect_class=defect,
        severity=Severity.HIGH,
        status=IssueStatus.RECEIVED,
        fingerprint=("f" * 63) + issue_id[-1],
    )
    store.add(issue)
    store.link_alert(
        issue_id,
        Alert(
            alert_ref=f"check:{issue_id}",
            source_kind=SourceKind.CHECK,
            rule_id=rule_id,
            location=Location(file=file, line=line),
            raw_severity=Severity.HIGH,
            snippet_fingerprint="s" * 64,
            defect_class=defect,
        ),
    )
    return issue


def make_reachable(store: MemoryStore, issue: Issue) -> Issue:
    orchestration = OrchestrationService(store, store, store)
    orchestration.apply(
        Transition.T1,
        TransitionContext(issue=issue),
        __import__("app.domain.enums", fromlist=["EventType"]).EventType.INGEST,
        "normalizer",
    )
    triaging = store.get(issue.issue_id)
    verdict = Verdict(
        verdict_id=f"V-{issue.issue_id}",
        issue_id=issue.issue_id,
        conclusion=VerdictConclusion.REACHABLE,
        confidence=0.9,
        taint_path=["app/main.py:user"],
        basis="static path",
        decided_by="tracer",
    )
    store.add_verdict(verdict)
    orchestration.apply(
        Transition.T2,
        TransitionContext(issue=triaging, verdict=verdict),
        __import__("app.domain.enums", fromlist=["EventType"]).EventType.VERDICT,
        "tracer",
    )
    return store.get(issue.issue_id)


class TemplateTest(unittest.TestCase):
    def setUp(self) -> None:
        self.store = MemoryStore()
        self.issue = make_issue(
            self.store,
            "ISS-1",
            DefectClass.SQL_INJECTION,
            "app/main.py",
            31,
            "py/sql-injection",
        )
        self.alert = self.store.alerts_for("ISS-1")[0]

    def test_sql_template_is_behavioral_and_marked(self) -> None:
        generated = render_test(self.issue, self.alert, TARGET)
        self.assertIn("AUTOGENERATED", generated.source)
        self.assertIn("ISS-1", generated.source)
        self.assertEqual(generated.behavior, "behavioral")
        self.assertIn("/user", generated.source)
        self.assertTrue(generated.relative_path.startswith("tests/security/"))

    def test_command_template_uses_static_assertion(self) -> None:
        issue = make_issue(self.store, "ISS-2", DefectClass.COMMAND_INJECTION, "app/main.py", 81, "py/command-injection")
        alert = self.store.alerts_for("ISS-2")[0]
        generated = render_test(issue, alert, TARGET)
        self.assertEqual(generated.behavior, "static")
        self.assertIn("os.popen", generated.source)

    def test_secret_template(self) -> None:
        issue = make_issue(self.store, "ISS-3", DefectClass.HARDCODED_SECRET, "app/config.py", 1, "py/hardcoded-secret")
        alert = self.store.alerts_for("ISS-3")[0]
        generated = render_test(issue, alert, TARGET)
        self.assertIn("字面量凭据", generated.source)

    def test_dependency_template(self) -> None:
        issue = Issue(
            issue_id="ISS-4",
            repo="verifix-target",
            code_version="abc123",
            defect_class=DefectClass.DEPENDENCY_CVE,
            severity=Severity.MEDIUM,
            status=IssueStatus.RECEIVED,
            fingerprint="4" * 64,
        )
        self.store.add(issue)
        self.store.link_alert(
            "ISS-4",
            Alert(
                alert_ref="check:dep:4",
                source_kind=SourceKind.GOVERNANCE,
                rule_id="dependency-cve",
                location=Location(file="requirements.txt", component="requests", component_version="2.19.1"),
                raw_severity=Severity.MEDIUM,
                snippet_fingerprint="d" * 64,
                defect_class=DefectClass.DEPENDENCY_CVE,
            ),
        )
        generated = render_test(issue, self.store.alerts_for("ISS-4")[0], TARGET)
        self.assertIn("requests==2.19.1", generated.source)


class ValidatorTest(unittest.TestCase):
    def test_rejects_constant_assertion(self) -> None:
        problems = validate_test_source("def test_x():\n    assert True\n")
        self.assertTrue(any("constant assertion" in item for item in problems))

    def test_rejects_skip_marker(self) -> None:
        source = "import unittest\n\n@unittest.skip('x')\ndef test_x():\n    pass\n"
        problems = validate_test_source(source)
        self.assertTrue(any("skip marker" in item for item in problems))

    def test_rejects_network_dependency(self) -> None:
        source = "import requests\n\ndef test_x():\n    requests.get('https://example.com')\n"
        problems = validate_test_source(source)
        self.assertTrue(any("network" in item for item in problems))

    def test_rejects_missing_marker(self) -> None:
        problems = validate_test_source("def test_x():\n    assert 1 == 1\n")
        self.assertIn("missing AUTOGENERATED marker", problems)

    def test_accepts_valid_generated_test(self) -> None:
        with TemporaryDirectory() as tmp:
            generated = render_test(
                make_issue(MemoryStore(), "ISS-9", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection"),
                Alert(
                    alert_ref="a",
                    source_kind=SourceKind.CHECK,
                    rule_id="py/sql-injection",
                    location=Location(file="app/main.py", line=31),
                    raw_severity=Severity.HIGH,
                    snippet_fingerprint="x" * 64,
                ),
                TARGET,
            )
        plugin = default_registry().by_class(DefectClass.SQL_INJECTION)
        assert plugin is not None
        self.assertEqual(validate_test_source(generated.source, plugin.assertion_policy()), [])


class ReproducerServiceTest(unittest.TestCase):
    def setUp(self) -> None:
        self.config = load_config()
        self.store = MemoryStore()
        self.service = ReproducerService(self.store, LocalTestExecutor(), self.config)

    def test_sql_injection_proves_red_before_patch(self) -> None:
        issue = make_issue(self.store, "ISS-5", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        make_reachable(self.store, issue)
        outcome = self.service.reproduce(self.store.get("ISS-5"), TARGET)
        self.assertIs(outcome.status, ReproductionStatus.PROVEN, outcome.message)
        self.assertIsNotNone(outcome.proof)
        proof = outcome.proof
        assert proof is not None
        self.assertEqual(proof.pre_patch_result.value, "FAIL")
        self.assertEqual(len(proof.fingerprint), 64)
        self.assertEqual(self.store.get("ISS-5").status, IssueStatus.PROVEN)

    def test_passing_test_is_repro_failed(self) -> None:
        with TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "app").mkdir()
            (root / "app" / "main.py").write_text(FIXED_COMMAND_APP, encoding="utf-8")
            issue = make_issue(self.store, "ISS-6", DefectClass.COMMAND_INJECTION, "app/main.py", 5, "py/command-injection")
            make_reachable(self.store, issue)
            outcome = self.service.reproduce(self.store.get("ISS-6"), root)
        self.assertIs(outcome.status, ReproductionStatus.REPRO_FAILED)
        self.assertIs(outcome.error_code, ErrorCode.REPRO_FAILED)
        self.assertEqual(self.store.get("ISS-6").status, IssueStatus.DISPOSED_L2)

    def test_infra_error_is_retried_and_not_business_failure(self) -> None:
        class InfraExecutor:
            def __init__(self) -> None:
                self.calls = 0

            def run_tests(self, workspace: Path, test_path: str) -> TestExecution:
                self.calls += 1
                return TestExecution(
                    exit_code=-1,
                    stdout="",
                    stderr="docker missing",
                    duration_ms=0,
                    timed_out=False,
                    backend="sandbox",
                    env_snapshot=EnvSnapshot(),
                    infra_error="docker missing",
                )

        executor = InfraExecutor()
        service = ReproducerService(self.store, executor, self.config)
        issue = make_issue(self.store, "ISS-7", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        make_reachable(self.store, issue)
        outcome = service.reproduce(self.store.get("ISS-7"), TARGET)
        self.assertIs(outcome.status, ReproductionStatus.INFRA_ERROR)
        self.assertEqual(executor.calls, 2)
        self.assertIn("重试", outcome.message)

    def test_unreachable_issue_cannot_reproduce(self) -> None:
        issue = make_issue(self.store, "ISS-8", DefectClass.SQL_INJECTION, "app/main.py", 31, "py/sql-injection")
        outcome = self.service.reproduce(self.store.get("ISS-8"), TARGET)
        self.assertIs(outcome.status, ReproductionStatus.NOT_READY)
        self.assertIs(outcome.error_code, ErrorCode.NO_VERDICT)


